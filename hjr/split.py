"""The dev/held-out task split: seeded, stratified by category, frozen in configs/split.toml.

Repairs may be designed only from dev boundaries; held-out tasks are for measuring them. Each
category is shuffled with its own seeded generator and its first round(40%) tasks go to dev, so
adding a task to one category never moves a task in another. Soak-only tasks are not split.
"""

from __future__ import annotations

import random
import tomllib
from collections import defaultdict
from pathlib import Path

from hjr.config import CONFIGS, global_seed
from hjr.schemas import Split

SPLIT_CONFIG = CONFIGS / "split.toml"
DEV_SHARE = 0.4


def _tasks(tasks_dir: Path) -> dict[str, str]:
    """Analysable task id -> category."""
    out = {}
    for toml in sorted(tasks_dir.glob("*/task.toml")):
        meta = tomllib.loads(toml.read_text(encoding="utf-8"))["metadata"]
        if not meta.get("soak_only"):
            out[meta["id"]] = meta["category"]
    return out


def make_split(tasks_dir: Path, seed: int) -> dict[str, Split]:
    by_category: dict[str, list[str]] = defaultdict(list)
    for task, category in _tasks(tasks_dir).items():
        by_category[category].append(task)
    split: dict[str, Split] = {}
    for category, tasks in sorted(by_category.items()):
        order = sorted(tasks)
        random.Random(f"{seed}:{category}").shuffle(order)
        n_dev = round(len(order) * DEV_SHARE)
        split |= {t: "dev" for t in order[:n_dev]} | {t: "heldout" for t in order[n_dev:]}
    return dict(sorted(split.items()))


def render(split: dict[str, Split], seed: int) -> str:
    lines = [
        "# Dev/held-out task split, generated by `hjr split` (hjr/split.py) and frozen before",
        f"# Phase 1. Seed {seed}; per category, a seeded shuffle puts round(40%) of tasks in dev.",
        "",
    ]
    for name in ("dev", "heldout"):
        tasks = [t for t, s in split.items() if s == name]
        lines.append(f"{name} = [")
        lines += [f'    "{t}",' for t in tasks]
        lines += ["]", ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def load_split(path: Path = SPLIT_CONFIG) -> dict[str, Split]:
    doc = tomllib.loads(path.read_text(encoding="utf-8"))
    return {t: name for name in ("dev", "heldout") for t in doc[name]}


def write_split(tasks_dir: Path, path: Path = SPLIT_CONFIG) -> dict[str, Split]:
    seed = global_seed()
    split = make_split(tasks_dir, seed)
    path.write_text(render(split, seed), encoding="utf-8", newline="\n")
    return split
